out, bundle = ROOT / "samples", []
for folder, name, fm, body in S:
    (out / folder).mkdir(parents=True, exist_ok=True)
    text = body + "\n"
    if fm:
        head = "\n".join(f"{k}: [{', '.join(v)}]" if isinstance(v, list) else f"{k}: {v}" for k, v in fm.items())
        text = f"---\n{head}\n---\n\n" + text
    (out / folder / name).write_text(text, encoding="utf-8")
