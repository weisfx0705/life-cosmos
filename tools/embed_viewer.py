#!/usr/bin/env python3
"""Copy viewer/template.html into builder/viewer-template.js as a JS string.

The builder opens universes from that string (not with fetch), so builder/index.html also
works when it is opened straight from disk (file://), on Mac and Windows alike.
Run after changing viewer/template.html:   python3 tools/embed_viewer.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
tpl = (ROOT / "viewer/template.html").read_text(encoding="utf-8")
assert "/*__DATA__*/" in tpl
js = "/* generated by tools/embed_viewer.py from viewer/template.html — do not edit by hand */\n" \
     "window.VIEWER_TEMPLATE = " + json.dumps(tpl, ensure_ascii=False).replace("</", "<\\/") + ";\n"
(ROOT / "builder/viewer-template.js").write_text(js, encoding="utf-8")
print("builder/viewer-template.js", len(js) // 1024, "KB")
